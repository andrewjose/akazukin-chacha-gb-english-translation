"""Generate font assets from tools/fontdef.py.
Outputs ($CHACHA_WORK/engine/font/):
  glyphs.png        glyph sheet (VWF, 16 per row, red bar = advance)  + fixed8.png (8x8 menu tiles)
  vwf_glyphs.bin    8 bytes/glyph (1bpp, MSB = left), codes 0x20..0x82
  vwf_widths.bin    1 byte/glyph advance in px
  font9000.bin      0x800-byte tile block for $9000: 00-3B blank (VWF canvas), 3C-55 A-Z, 56-6F a-z,
                    70 ? 71 ! 72 - 73 . ; 74-7F copied from the original font (heart = WAIT cursor, note, drop, cursor, frame pieces)
  fixed.tbl         fixed 8x8 encoding (tile index = code)
"""
import sys,os
T=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,T)
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','common')); import paths
E=paths.ENGINE_WORK
import fontdef
from lz import decompress
from PIL import Image
FD=os.path.join(E,'font'); os.makedirs(FD,exist_ok=True)
FIRST=0x20; LAST=0x82
CODES={chr(c):c for c in range(0x20,0x7F)}; CODES.update(fontdef.SPECIAL_CODES)
INV={v:k for k,v in CODES.items()}
def rows_bits(rows):
    return [int(r.replace('#','1').replace('.','0').ljust(8,'0')[:8],2) for r in rows]
glyphs=bytearray(); widths=bytearray()
for c in range(FIRST,LAST+1):
    k=INV.get(c)
    if k is None: glyphs+=bytes(8); widths.append(0); continue
    rows,adv=fontdef.G[k]; assert len(rows[0])<=8 and adv<=8,k
    glyphs+=bytes(rows_bits(rows)); widths.append(adv)
open(os.path.join(FD,'vwf_glyphs.bin'),'wb').write(glyphs)
open(os.path.join(FD,'vwf_widths.bin'),'wb').write(widths)
# sheet
n=LAST-FIRST+1; S=4
im=Image.new('RGB',(16*10*S,((n+15)//16)*11*S),(200,200,200))
for i in range(n):
    x0=(i%16)*10; y0=(i//16)*11
    for y in range(8):
        for x in range(8):
            on=glyphs[i*8+y]>>(7-x)&1
            col=(0,0,0) if on else ((255,255,255) if x<widths[i] else (235,235,235))
            for a in range(S):
                for b in range(S): im.putpixel(((x0+x)*S+a,(y0+y)*S+b),col)
    for x in range(widths[i]):
        for a in range(S):
            for b in range(S//2): im.putpixel(((x0+x)*S+a,(y0+9)*S+b),(220,0,0))
im.save(os.path.join(FD,'glyphs.png'))
# fixed 8x8 tiles
orig=open(paths.rom_path(),'rb').read()
ofont=decompress(orig,0xD976,0x800)[0]
blk=bytearray(0x800)
FIX={}
for i,ch in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'): FIX[ch]=0x3C+i
for i,ch in enumerate('abcdefghijklmnopqrstuvwxyz'): FIX[ch]=0x56+i
FIX.update({'?':0x70,'!':0x71,'-':0x72,'.':0x73})
def tile_from(rows):
    # menu font: the VWF art emboldened by 1 px (closer to the weight of the original kana), centred in the cell
    w=len(rows[0])+1; x0=(8-w)//2; t=bytearray(16)
    for y,b in enumerate(rows_bits(rows)):
        b=(b|(b>>1))&0xFF
        v=b>>x0; t[2*y]=v; t[2*y+1]=v
    return t
for ch,code in FIX.items():
    blk[code*16:code*16+16]=tile_from(fontdef.G[ch][0])
blk[0x74*16:0x80*16]=ofont[0x74*16:0x80*16]
open(os.path.join(FD,'font9000.bin'),'wb').write(blk)
tbl=['# fixed 8x8 menu font (tile index = code), generated by make_font.py']
tbl+=['%02X=%s'%(v,k) for k,v in sorted(FIX.items(),key=lambda kv:kv[1])]
tbl+=['74=<HEART>','75=<NOTE>','76={drop}','FF= ']
open(os.path.join(FD,'fixed.tbl'),'w').write('\n'.join(tbl)+'\n')
im2=Image.new('RGB',(16*9*S,8*9*S),(255,0,255))
for t in range(128):
    for y in range(8):
        lo,hi=blk[t*16+2*y],blk[t*16+2*y+1]
        for x in range(8):
            c=((lo>>(7-x))&1)|(((hi>>(7-x))&1)<<1); v=255-c*85
            for a in range(S):
                for b in range(S): im2.putpixel((((t%16)*9+x)*S+a,((t//16)*9+y)*S+b),(v,v,v))
im2.save(os.path.join(FD,'fixed8.png'))
print('glyphs',n,'avg width a-z %.2f'%(sum(widths[ord(c)-FIRST] for c in 'abcdefghijklmnopqrstuvwxyz')/26))
